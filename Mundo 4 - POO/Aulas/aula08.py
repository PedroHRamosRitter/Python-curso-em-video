# Abstração

# A prática de ignorar o irrelevante e se focar estritamente no essencial

# Dessa maneira, o usuário não precisa saber detalhes da implementação
# e passa a se focar apena na interfaca pública que está disponível

# Existe a abstração de dados, que acontece quando ignoramos informações desnecessárias
# para o escopo do projeto.

# Existe a abstração de processos, quando não precisamos saber como um metódo faz
# seu trabalho, apenas sabe que ele existe pela interface

# Classe Abstrata não vai servir para virar objeto, mas as subclasses virarem objetos
# Exemplo Controle genérico, sendo a classe abstrata e o controle remoto da samgung
# como subclasse e virando objeto

# Uma classes abstrata nunca será instanciada, já que ela será usada apenas como
# base para as subclasses.

# Ao definir um conjunto de metódos abstratos, dizemos que estamos criando a interface pública da classe.

# Uma classe abstrata pode ter métodos abstratos que deverão ser obrigatoriamente
# implementados nas subclasses.

# Mas uma classe abstrata pode ter métodos concretos se eles funcionarem da mesma
# maneira para todas as subclasses (DRY).



# Vantagens da Abstraçao:

# Maior legibilidade
# Padronização
# Simplificação
# Segurança

